import 'dart:typed_data';

import 'package:flutter/services.dart' show rootBundle;
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

import '../../core/dates.dart';
import '../../core/money.dart';
import '../../domain/report/csv_report.dart';

/// Month-wise transaction report as a PDF: summary, spend by category, then every entry.
/// Built with the bundled Manrope so ₹ and Indian names render; fully offline.
abstract final class PdfReport {
  static pw.Font? _regular, _bold;

  static Future<void> _fonts() async {
    _regular ??= pw.Font.ttf(await rootBundle.load('assets/fonts/Manrope-Regular.ttf'));
    _bold ??= pw.Font.ttf(await rootBundle.load('assets/fonts/Manrope-Bold.ttf'));
  }

  static Future<Uint8List> build(List<ReportRow> rows, {required String title, String? subtitle}) async {
    await _fonts();
    final theme = pw.ThemeData.withFont(base: _regular!, bold: _bold!).copyWith(
      defaultTextStyle: pw.TextStyle(font: _regular, fontSize: 9.5, color: PdfColors.grey900),
    );
    const blue = PdfColor.fromInt(0xFF1B539A);
    const muted = PdfColors.grey600;

    var income = 0, expense = 0;
    final byCat = <String, int>{};
    for (final r in rows) {
      switch (r.type) {
        case 'salary' || 'extra_income':
          income += r.amount;
        case 'expense':
          expense += r.amount;
          byCat[r.category ?? 'Other'] = (byCat[r.category ?? 'Other'] ?? 0) + r.amount;
      }
    }
    final cats = byCat.entries.toList()..sort((a, b) => b.value.compareTo(a.value));
    String inr(int p) => Money.format(p, showPaise: true);

    pw.Widget stat(String label, String value, {PdfColor color = PdfColors.grey900}) => pw.Expanded(
          child: pw.Container(
            padding: const pw.EdgeInsets.all(10),
            decoration: pw.BoxDecoration(color: PdfColors.grey100, borderRadius: pw.BorderRadius.circular(8)),
            child: pw.Column(crossAxisAlignment: pw.CrossAxisAlignment.start, children: [
              pw.Text(label, style: const pw.TextStyle(fontSize: 8, color: muted)),
              pw.SizedBox(height: 3),
              pw.Text(value, style: pw.TextStyle(font: _bold, fontSize: 13, color: color)),
            ]),
          ),
        );

    final doc = pw.Document(title: title, author: 'BRUNT', theme: theme);
    doc.addPage(pw.MultiPage(
      pageFormat: PdfPageFormat.a4,
      margin: const pw.EdgeInsets.fromLTRB(36, 40, 36, 36),
      footer: (ctx) => pw.Row(mainAxisAlignment: pw.MainAxisAlignment.spaceBetween, children: [
        pw.Text('Generated by BRUNT on ${Dates.short(DateTime.now())} ${DateTime.now().year} · stored only on your phone',
            style: const pw.TextStyle(fontSize: 7.5, color: muted)),
        pw.Text('Page ${ctx.pageNumber} of ${ctx.pagesCount}', style: const pw.TextStyle(fontSize: 7.5, color: muted)),
      ]),
      build: (ctx) => [
        pw.Row(crossAxisAlignment: pw.CrossAxisAlignment.end, children: [
          pw.Expanded(
            child: pw.Column(crossAxisAlignment: pw.CrossAxisAlignment.start, children: [
              pw.Text('BRUNT', style: pw.TextStyle(font: _bold, fontSize: 10, color: blue, letterSpacing: 3)),
              pw.SizedBox(height: 2),
              pw.Text(title, style: pw.TextStyle(font: _bold, fontSize: 20)),
              if (subtitle != null) pw.Text(subtitle, style: const pw.TextStyle(fontSize: 9, color: muted)),
            ]),
          ),
          pw.Text('${rows.length} entries', style: const pw.TextStyle(fontSize: 9, color: muted)),
        ]),
        pw.SizedBox(height: 14),
        pw.Row(children: [
          stat('Income', inr(income), color: const PdfColor.fromInt(0xFF1E8E5A)),
          pw.SizedBox(width: 8),
          stat('Spent', inr(expense)),
          pw.SizedBox(width: 8),
          stat('Net', inr(income - expense), color: income - expense < 0 ? const PdfColor.fromInt(0xFFC0392B) : blue),
        ]),
        if (cats.isNotEmpty) ...[
          pw.SizedBox(height: 16),
          pw.Text('Spend by category', style: pw.TextStyle(font: _bold, fontSize: 11)),
          pw.SizedBox(height: 6),
          pw.TableHelper.fromTextArray(
            headers: ['Category', 'Amount', 'Share'],
            data: [
              for (final c in cats) [c.key, inr(c.value), expense == 0 ? '' : '${c.value * 100 ~/ expense}%'],
            ],
            headerStyle: pw.TextStyle(font: _bold, fontSize: 8.5, color: PdfColors.white),
            headerDecoration: const pw.BoxDecoration(color: blue),
            cellStyle: const pw.TextStyle(fontSize: 8.5),
            cellAlignments: {1: pw.Alignment.centerRight, 2: pw.Alignment.centerRight},
            columnWidths: {0: const pw.FlexColumnWidth(3), 1: const pw.FlexColumnWidth(1.4), 2: const pw.FlexColumnWidth(0.8)},
            oddRowDecoration: const pw.BoxDecoration(color: PdfColors.grey100),
            border: null,
          ),
        ],
        pw.SizedBox(height: 16),
        pw.Text('Transactions', style: pw.TextStyle(font: _bold, fontSize: 11)),
        pw.SizedBox(height: 6),
        pw.TableHelper.fromTextArray(
          headers: ['Date', 'Description', 'Category', 'Account', 'Amount'],
          data: [
            for (final r in rows)
              [
                _date(r.date),
                r.note?.isNotEmpty == true ? r.note! : (r.type == 'transfer' ? 'Transfer' : r.category ?? _type(r.type)),
                r.type == 'transfer' ? 'Transfer' : (r.type == 'adjustment' ? 'Adjustment' : r.category ?? ''),
                r.type == 'transfer' ? '${r.account ?? ''} → ${r.toAccount ?? ''}' : [r.account, if (r.via != null) 'via ${r.via}'].whereType<String>().join(' '),
                _signed(r),
              ],
          ],
          headerStyle: pw.TextStyle(font: _bold, fontSize: 8.5, color: PdfColors.white),
          headerDecoration: const pw.BoxDecoration(color: blue),
          cellStyle: const pw.TextStyle(fontSize: 8.5),
          cellAlignments: {4: pw.Alignment.centerRight},
          columnWidths: {
            0: const pw.FlexColumnWidth(1.1),
            1: const pw.FlexColumnWidth(2.6),
            2: const pw.FlexColumnWidth(1.6),
            3: const pw.FlexColumnWidth(2.2),
            4: const pw.FlexColumnWidth(1.4),
          },
          oddRowDecoration: const pw.BoxDecoration(color: PdfColors.grey100),
          border: null,
        ),
        pw.SizedBox(height: 10),
        pw.Align(
          alignment: pw.Alignment.centerRight,
          child: pw.Text('Income ${inr(income)}   ·   Spent ${inr(expense)}   ·   Net ${inr(income - expense)}',
              style: pw.TextStyle(font: _bold, fontSize: 9)),
        ),
      ],
    ));
    return doc.save();
  }

  static String _date(String iso) {
    final d = Dates.parseIso(iso);
    return '${d.day.toString().padLeft(2, '0')} ${Dates.monthShort[d.month - 1]} ${d.year}';
  }

  static String _type(String t) => switch (t) {
        'salary' => 'Salary',
        'extra_income' => 'Extra income',
        'adjustment' => 'Balance adjustment',
        _ => 'Expense',
      };

  static String _signed(ReportRow r) => switch (r.type) {
        'expense' => '− ${Money.format(r.amount, showPaise: true)}',
        'salary' || 'extra_income' => '+ ${Money.format(r.amount, showPaise: true)}',
        _ => Money.format(r.amount, showPaise: true), // transfers unsigned; adjustments carry their own sign
      };
}
